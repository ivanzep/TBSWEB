#!/usr/bin/env node
/*
 * GENERATOR — regenerates reference/sections-index.js and every
 * reference/<id>/data.js by scanning what's actually on disk. Same idea as
 * generate-version-data.js (see that file for the full rationale on why a
 * scan step exists at all instead of runtime discovery), applied to the
 * Reference Images moodboard page instead of design versions — sibling
 * script, shares its low-level scanning utilities via lib/scan-common.js.
 *
 *   node scripts/generate-reference-data.js
 *
 * Per section folder, only reference/<id>/meta.json is hand-authored
 * ({ title, note }, note optional) — everything else (which images exist,
 * their order, their captions, which section folders exist at all) is
 * derived from the filesystem the same way a design version's images are:
 * natural sort, caption from embedded Title metadata or a humanized
 * filename otherwise. No thumb/hero/videos/pager concepts here — a
 * reference section is just a titled collection of images.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const {
  listContentFolders, readJsonIfExists, buildImages, imageHasMetadataTitle, jsStringLiteral
} = require("./lib/scan-common.js");

const REFERENCE_DIR = path.join(__dirname, "..", "reference");

function renderDataJs(id, meta, images) {
  const imagesJs = images.map((img) =>
    `    { src: ${jsStringLiteral(img.src)}, caption: ${jsStringLiteral(img.caption)} }`
  ).join(",\n");

  return `/* AUTO-GENERATED by scripts/generate-reference-data.js — do not hand-edit.
 * Edit reference/${id}/meta.json for title/note, add/remove files in
 * reference/${id}/assets/ for images — then re-run:
 * node scripts/generate-reference-data.js
 */
window.SECTIONS = window.SECTIONS || {};
window.SECTIONS[${jsStringLiteral(id)}] = {
  id: ${jsStringLiteral(id)},
  title: ${jsStringLiteral(meta.title)},
  note: ${jsStringLiteral(meta.note || "")},
  images: [
${imagesJs}
  ]
};
`;
}

function renderIndexJs(ids) {
  const idsJs = ids.map((id) => "  " + jsStringLiteral(id)).join(",\n");
  return `/* AUTO-GENERATED by scripts/generate-reference-data.js — do not hand-edit.
 * Reflects whatever section folders currently exist under reference/
 * (excluding _template). Order is natural-sort by folder name, which is
 * also the display order on the Reference Images page. Re-run after
 * adding/removing a section folder: node scripts/generate-reference-data.js
 */
window.SECTION_IDS = [
${idsJs}
];
`;
}

function main() {
  if (!fs.existsSync(REFERENCE_DIR)) {
    console.log("[skip] no reference/ folder — nothing to scan");
    return;
  }

  const ids = listContentFolders(REFERENCE_DIR);

  ids.forEach((id) => {
    const dir = path.join(REFERENCE_DIR, id);
    const assetsDir = path.join(dir, "assets");
    const metaPath = path.join(dir, "meta.json");

    if (!fs.existsSync(assetsDir)) {
      console.warn("[skip] " + id + ": no assets/ folder");
      return;
    }
    const meta = readJsonIfExists(metaPath, null);
    if (!meta || !meta.title) {
      console.warn("[skip] " + id + ": missing meta.json ({ title })");
      return;
    }

    const images = buildImages(assetsDir);
    fs.writeFileSync(path.join(dir, "data.js"), renderDataJs(id, meta, images));

    const metaCount = images.filter((img) => imageHasMetadataTitle(assetsDir, img._file)).length;
    console.log("[ok] " + id + ": " + images.length + " image(s) (" + metaCount + " with metadata title)");
  });

  fs.writeFileSync(path.join(REFERENCE_DIR, "sections-index.js"), renderIndexJs(ids));
  console.log("[ok] sections-index.js: " + (ids.length ? ids.join(", ") : "(none yet)"));
}

main();
